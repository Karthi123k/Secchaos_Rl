def run_anova_on_rewards(rewards_dict: Dict[str, List[float]]):
    groups = list(rewards_dict.values())
    f_stat, p_val = stats.f_oneway(*groups)
    return {"F": float(f_stat), "p": float(p_val)}

def run_tukey(rewards_dict: Dict[str, List[float]]):
    data = []
    labels = []
    for name, arr in rewards_dict.items():
        data.extend(arr)
        labels.extend([name]*len(arr))
    df = pd.DataFrame({"y":data, "group": labels})
    tukey = mc.pairwise_tukeyhsd(df["y"], df["group"])
    res_df = pd.DataFrame(data=tukey._results_table.data[1:], columns=tukey._results_table.data[0])
    return {"summary_df": res_df, "summary_text": tukey.summary().as_text()}

def cohens_d(x: List[float], y: List[float]) -> float:
    x = np.array(x, dtype=float); y = np.array(y, dtype=float)
    nx, ny = len(x), len(y)
    dof = nx + ny - 2
    pooled_std = np.sqrt(((nx-1)*x.var(ddof=1) + (ny-1)*y.var(ddof=1)) / dof) if dof>0 else np.std(np.concatenate([x,y]), ddof=1)
    if pooled_std == 0:
        return 0.0
    return float((x.mean() - y.mean()) / pooled_std)

