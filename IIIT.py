class SecChaosEnv(gym.Env):
    metadata = {"render_modes": ["human"]}
    def __init__(self, seed:int = None, lambda_f: float = None, max_steps: int = None):
        super().__init__()
        self.seed = int(seed if seed is not None else cfg.SEED)
        self._rng = np.random.default_rng(self.seed)
        self.lambda_f = float(lambda_f if lambda_f is not None else cfg.FAULT_LAMBDA)
        self.max_steps = int(max_steps if max_steps is not None else cfg.ENV_MAX_STEPS)
        self.step_count = 0

        self.injector = SecurityFaultInjector(seed=self.seed, lambda_f=self.lambda_f)
        self.dep_graph = DependencyGraph()
        self.monitor = MonitoringLayer()
        self.mitigation = MitigationEngine(seed=self.seed)
        self.reward_engine = RewardEngine(alpha=cfg.ALPHA, beta=cfg.BETA, gamma=cfg.GAMMA, delta=cfg.DELTA, lam=cfg.LAMBDA, mu=cfg.MU, Tmax=100.0)

        self.state: Dict[str, Any] = {}
        self._init_state()
        self.observation_space = spaces.Box(low=0.0, high=1.0, shape=(9,), dtype=np.float32)
        self.action_space = spaces.Discrete(9)

    def _init_state(self):
        self.state = {
            "certificate_risk": float(self._rng.uniform(0.05, 0.2)),
            "dependency_risk": float(self._rng.uniform(0.05, 0.25)),
            "secret_risk": float(self._rng.uniform(0.01, 0.12)),
            "rbac_risk": float(self._rng.uniform(0.02, 0.2)),
            "authentication_risk": float(self._rng.uniform(0.03, 0.2)),
            "patch_level": float(self._rng.uniform(0.4, 0.8)),
            "attack_probability": float(self._rng.uniform(0.01, 0.05)),
            "availability": float(self._rng.uniform(0.95, 0.99)),
            "recovery_time": 0.0
        }
        self.dep_graph.reset()
        self.faults: Dict[str, Fault] = {}
        self.mitigation.clear()

    def reset(self, seed: int = None, options: Dict = None):
        if seed is not None:
            self.seed = int(seed)
            self._rng = np.random.default_rng(self.seed)
            self.injector = SecurityFaultInjector(seed=self.seed, lambda_f=self.lambda_f)
        self.step_count = 0
        self._init_state()
        obs = self.monitor.transform_to_state_vector({**self.state, "env_max_steps": self.max_steps})
        return obs, {}

    def step(self, action: int):
        self.step_count += 1
        prev_state = dict(self.state)

        # Fault injection
        if self._rng.random() < cfg.FAULT_INJECTION_RATE:
            new_faults = self.injector.inject_multiple_faults(step=self.step_count)
            for f in new_faults:
                fid = f"{f.code}_{f.injected_step}_{self._rng.integers(1_000_000)}"
                self.faults[fid] = f
                mapping = {"F1":"Gateway","F2":"User","F3":"User","F4":"Authentication","F5":"Authentication","F6":"Order","F7":"Inventory","F8":"Gateway"}
                svc = mapping.get(f.code, "Gateway")
                self.dep_graph.apply_fault_to_service(svc, f.severity * f.scope, step=self.step_count)
                self.dep_graph.propagate_cascade(svc, f.severity, f.scope, gamma=0.4)

        # Update state from graph aggregates
        agg_risk = self.dep_graph.aggregate_system_risk()
        agg_avail = self.dep_graph.aggregate_availability()
        self.state["dependency_risk"] = float(np.clip(0.5 * self.state["dependency_risk"] + 0.5 * agg_risk, 0.0, 1.0))
        self.state["availability"] = float(np.clip(0.5 * self.state["availability"] + 0.5 * agg_avail, 0.0, 1.0))

        # Execute action scheduling
        action_cost = self.mitigation.execute_action(action, self.step_count)

        # Evolve faults
        expired = self.injector.fault_expiration(self.faults)
        for fid in expired:
            self.faults.pop(fid, None)

        # Apply due mitigations
        due = self.mitigation.schedule_delayed_action(self.step_count)
        for act in due:
            self.state = self.mitigation.apply_effect(int(act), self.state)

        # Transition model: propagation and stochastic noise
        risks = np.array([self.state["certificate_risk"], self.state["dependency_risk"], self.state["secret_risk"], self.state["rbac_risk"], self.state["authentication_risk"]], dtype=float)
        prop_matrix = np.array([[1.0,0.05,0.02,0.03,0.02],[0.04,1.0,0.03,0.04,0.03],[0.03,0.03,1.0,0.02,0.02],[0.02,0.04,0.03,1.0,0.03],[0.02,0.02,0.02,0.03,1.0]], dtype=float)
        propagated = prop_matrix.dot(risks) - risks
        noise = self._rng.normal(0.0, 0.02, size=5) * (1.0 + risks)
        new_risks = np.clip(risks + 0.5 * propagated + noise, 0.0, 1.0)
        self.state["certificate_risk"], self.state["dependency_risk"], self.state["secret_risk"], self.state["rbac_risk"], self.state["authentication_risk"] = new_risks.tolist()

        total_risk = float(new_risks.sum())
        base_attack = 0.01 + 0.35 * (total_risk / 5.0) * (1.0 - self.state["patch_level"])
        self.state["attack_probability"] = float(np.clip(base_attack + self._rng.normal(0.0, 0.01), 0.0, 1.0))

        attacked = (self._rng.random() < self.state["attack_probability"])
        if attacked:
            impact = float(np.clip(0.05 + 0.5 * (total_risk / 5.0) * self._rng.random(), 0.01, 0.8))
            self.state["availability"] = float(np.clip(self.state["availability"] - impact, 0.0, 1.0))
            self.state["recovery_time"] = 0.0
        else:
            self.state["availability"] = float(np.clip(self.state["availability"] + 0.01 * self.state["patch_level"], 0.0, 1.0))
            self.state["recovery_time"] = float(self.state.get("recovery_time", 0.0) + 1.0)

        # Reward (uses prev and next state)
        reward = self.reward_engine.compute_reward(prev_state, self.state, int(action), self.faults, float(action_cost))

        # Observation
        raw = dict(self.state)
        raw["env_max_steps"] = self.max_steps
        obs = self.monitor.transform_to_state_vector(raw)

        truncated = bool(self.step_count >= self.max_steps)
        terminated = bool((self.state["availability"] < 0.3) or (total_risk > 4.0) or (total_risk < 0.05))

        info = {"step":self.step_count, "fault_count":len(self.faults), "due_actions":due, "action_cost":action_cost, "attack_probability":self.state["attack_probability"], "availability":self.state["availability"]}
        return obs, float(reward), bool(terminated), bool(truncated), info

    def render(self, mode="human"):
        s = self.state
        print(f"[t={self.step_count}] cert={s['certificate_risk']:.3f} dep={s['dependency_risk']:.3f} secret={s['secret_risk']:.3f} rbac={s['rbac_risk']:.3f} auth={s['authentication_risk']:.3f} patch={s['patch_level']:.2f} atk={s['attack_probability']:.3f} avail={s['availability']:.3f} rec_t={s['recovery_time']:.1f}")

    def close(self):
        pass

