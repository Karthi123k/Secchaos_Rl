from dataclasses import dataclass
@dataclass
class Fault:
    code: str
    name: str
    severity: float
    duration: int
    scope: float
    detectability: float
    injected_step: int

FAULT_DEFS = {
    "F1":"Expired TLS Certificate",
    "F2":"Vulnerable Dependency",
    "F3":"Secret Leakage",
    "F4":"RBAC Misconfiguration",
    "F5":"Weak Authentication",
    "F6":"Excessive Privileges",
    "F7":"Missing Security Patch",
    "F8":"API Exposure"
}

class SecurityFaultInjector:
    def __init__(self, seed: int = None, lambda_f: float = None):
        self.seed = int(seed if seed is not None else cfg.SEED)
        self._rng = np.random.default_rng(self.seed)
        self.lambda_f = float(lambda_f if lambda_f is not None else cfg.FAULT_LAMBDA)

    def sample_n_faults(self) -> int:
        return int(self._rng.poisson(self.lambda_f))

    def _create_fault(self, code: str, step: int) -> Fault:
        base = {
            "F1": {"sev_mu":0.6,"dur_mu":10,"scope_mu":0.3,"det_mu":0.8},
            "F2": {"sev_mu":0.7,"dur_mu":20,"scope_mu":0.6,"det_mu":0.4},
            "F3": {"sev_mu":0.8,"dur_mu":15,"scope_mu":0.5,"det_mu":0.3},
            "F4": {"sev_mu":0.6,"dur_mu":12,"scope_mu":0.5,"det_mu":0.5},
            "F5": {"sev_mu":0.6,"dur_mu":14,"scope_mu":0.4,"det_mu":0.6},
            "F6": {"sev_mu":0.7,"dur_mu":18,"scope_mu":0.55,"det_mu":0.35},
            "F7": {"sev_mu":0.65,"dur_mu":22,"scope_mu":0.6,"det_mu":0.45},
            "F8": {"sev_mu":0.6,"dur_mu":16,"scope_mu":0.5,"det_mu":0.5}
        }[code]
        severity = float(np.clip(self._rng.normal(base["sev_mu"], 0.1), 0.0, 1.0))
        duration = int(max(1, int(self._rng.integers(max(1, base["dur_mu"]-5), base["dur_mu"]+5))))
        scope = float(np.clip(self._rng.normal(base["scope_mu"], 0.15), 0.01, 1.0))
        detectability = float(np.clip(self._rng.normal(base["det_mu"], 0.15), 0.0, 1.0))
        return Fault(code, FAULT_DEFS[code], severity, duration, scope, detectability, int(step))

    def inject_fault(self, step: int) -> Fault:
        code = self._rng.choice(list(FAULT_DEFS.keys()))
        return self._create_fault(code, step)

    def inject_multiple_faults(self, step: int) -> List[Fault]:
        n = self.sample_n_faults()
        return [self._create_fault(self._rng.choice(list(FAULT_DEFS.keys())), step) for _ in range(n)]

    def fault_expiration(self, faults: Dict[str, Fault]) -> List[str]:
        expired = []
        for fid, f in list(faults.items()):
            f.duration -= 1
            if f.duration <= 0:
                expired.append(fid)
        return expired

    def fault_detection(self, fault: Fault) -> bool:
        return self._rng.random() < float(fault.detectability)

