class DependencyGraph:
    def __init__(self):
        self.G = nx.DiGraph()
        self._build_graph()

    def _build_graph(self):
        nodes = ["Gateway","Authentication","User","Payment","Order","Inventory","Notification"]
        for n in nodes:
            self.G.add_node(n, risk=0.0, availability=1.0, last_fault_step=None)
        edges = [("Gateway","Authentication"), ("Authentication","User"), ("User","Order"), ("Order","Payment"), ("Payment","Inventory"), ("Inventory","Notification"), ("User","Payment")]
        self.G.add_edges_from(edges)

    def services(self) -> List[str]:
        return list(self.G.nodes)

    def apply_fault_to_service(self, service: str, fault_impact: float, step: int):
        if service not in self.G:
            return
        cur = float(self.G.nodes[service].get("risk", 0.0))
        self.G.nodes[service]["risk"] = float(np.clip(cur + fault_impact, 0.0, 1.0))
        self.G.nodes[service]["last_fault_step"] = int(step)
        # availability drop proportional
        self.G.nodes[service]["availability"] = float(np.clip(self.G.nodes[service]["availability"] - 0.05 * fault_impact, 0.0, 1.0))

    def propagate_cascade(self, source: str, severity: float, scope: float, gamma: float = 0.3):
        if source not in self.G:
            return
        visited = set()
        queue = [(source, 0)]
        while queue:
            node, dist = queue.pop(0)
            if node in visited:
                continue
            visited.add(node)
            impact = severity * scope * (gamma ** dist)
            cur = float(self.G.nodes[node].get("risk", 0.0))
            self.G.nodes[node]["risk"] = float(np.clip(cur + impact, 0.0, 1.0))
            self.G.nodes[node]["availability"] = float(np.clip(self.G.nodes[node]["availability"] - 0.05 * impact, 0.0, 1.0))
            for succ in self.G.successors(node):
                queue.append((succ, dist+1))

    def aggregate_system_risk(self) -> float:
        risks = [self.G.nodes[n].get("risk", 0.0) for n in self.G.nodes]
        return float(np.mean(risks)) if risks else 0.0

    def aggregate_availability(self) -> float:
        av = [self.G.nodes[n].get("availability", 1.0) for n in self.G.nodes]
        return float(np.mean(av)) if av else 1.0

    def reset(self):
        for n in self.G.nodes:
            self.G.nodes[n]["risk"] = 0.0
            self.G.nodes[n]["availability"] = 1.0
            self.G.nodes[n]["last_fault_step"] = None

