def rollout_episode(env: SecChaosEnv, model, deterministic: bool = True):
    obs, _ = env.reset()
    done=False
    step=0
    total_reward=0.0
    history={"total_risk":[],"attack_probability":[],"availability":[],"recovery_time":[],"episode_reward":0.0,"actions":[]}
    while step < env.max_steps and not done:
        if model is None:
            action = env.action_space.sample()
        else:
            action, _ = model.predict(obs, deterministic=deterministic)
            if isinstance(action, (list, tuple, np.ndarray)):
                action = int(np.array(action).squeeze().tolist())
        history["actions"].append(int(action))
        obs, reward, terminated, truncated, info = env.step(int(action))
        total_reward += float(reward)
        history["total_risk"].append(float(sum(obs[:5])))
        history["attack_probability"].append(float(obs[6]))
        history["availability"].append(float(obs[7]))
        history["recovery_time"].append(float(obs[8]))
        history["episode_reward"]= total_reward
        done = bool(terminated or truncated)
        step += 1
    return history

def evaluate_model(model, n_episodes:int = None):
    n_episodes = int(n_episodes if n_episodes is not None else cfg.N_EVAL)
    results=[]
    for i in range(n_episodes):
        env = SecChaosEnv(seed=cfg.SEED + i, lambda_f=cfg.FAULT_LAMBDA, max_steps=cfg.ENV_MAX_STEPS)
        h = rollout_episode(env, model)
        results.append(h)
        try:
            env.close()
        except Exception:
            pass
    return results

def compute_episode_metrics(history):
    total_risk = np.array(history.get("total_risk", []), dtype=float)
    attack_p = np.array(history.get("attack_probability", []), dtype=float)
    availability = np.array(history.get("availability", []), dtype=float)
    recovery_time = np.array(history.get("recovery_time", []), dtype=float)
    ep_reward = float(history.get("episode_reward", 0.0))
    if total_risk.size==0:
        risk_reduction=0.0; attack_success=0.0; avg_avail=1.0; mttr=float(cfg.ENV_MAX_STEPS)
    else:
        risk_reduction = float((total_risk[0]-total_risk[-1])/max(total_risk[0],1e-8))
        attack_success = float(np.mean(attack_p)) if attack_p.size>0 else 0.0
        avg_avail = float(np.mean(availability)) if availability.size>0 else 1.0
        recovered = np.where(total_risk < 0.05)[0]
        mttr = float(recovered[0]) if recovered.size>0 else float(cfg.ENV_MAX_STEPS)
    Tmax = cfg.ENV_MAX_STEPS * 2
    lrec = np.mean(1.0/(1.0 + recovery_time / Tmax)) if recovery_time.size>0 else 1.0
    resilience = 0.4*max(0.0,min(1.0,risk_reduction)) + 0.4*max(0.0,min(1.0,avg_avail)) + 0.2*lrec
    return {"risk_reduction":risk_reduction, "attack_success_rate":attack_success, "availability":avg_avail, "mttr":mttr, "recovery_efficiency":lrec, "resilience_score":resilience, "episode_reward":ep_reward}

