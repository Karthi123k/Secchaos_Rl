class ThreatAwareFeatureExtractor(BaseFeaturesExtractor):
    def __init__(self, observation_space: spaces.Box, features_dim: int = 256):
        super().__init__(observation_space, features_dim)
        obs_dim = observation_space.shape[0]
        self.obs_dim = obs_dim
        self.mlp = nn.Sequential(
            nn.Linear(obs_dim, 256),
            nn.Tanh(),
            nn.Linear(256, 256),
            nn.Tanh()
        )
        self.attn_net = nn.Sequential(
            nn.Linear(5, 64),
            nn.Tanh(),
            nn.Linear(64, 5)
        )
        self.attn_proj = nn.Sequential(
            nn.Linear(5, features_dim),
            nn.Tanh(),
            nn.Linear(features_dim, features_dim),
            nn.Sigmoid()
        )
        self.ln = nn.LayerNorm(features_dim)
        self._features_dim = features_dim

    def forward(self, observations: torch.Tensor) -> torch.Tensor:
        features = self.mlp(observations)
        threat_slice = observations[:, :5]
        logits = self.attn_net(threat_slice)
        weights = F.softmax(logits, dim=-1)
        gate = self.attn_proj(weights)
        gated = features * gate
        out = self.ln(gated + 0.05 * features)
        return out

