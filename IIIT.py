class MitigationEngine:
    def __init__(self, seed: int = None):
        self.seed = int(seed if seed is not None else cfg.SEED)
        self._rng = np.random.default_rng(self.seed)
        self.queue: List[Tuple[int,int]] = []

    def execute_action(self, action_id: int, current_step: int) -> float:
        spec = ACTION_SPECS.get(int(action_id), ACTION_SPECS[0])
        apply_at = int(current_step + spec["delay"])
        self.queue.append((apply_at, int(action_id)))
        return float(spec["cost"])

    def schedule_delayed_action(self, current_step: int) -> List[int]:
        to_apply = [act for (t,act) in self.queue if t <= current_step]
        self.queue = [(t,a) for (t,a) in self.queue if t > current_step]
        return to_apply

    def apply_effect(self, action_id: int, state: Dict[str, Any]) -> Dict[str, Any]:
        spec = ACTION_SPECS.get(int(action_id), ACTION_SPECS[0])
        eff = spec["eff"]
        risks = np.array([state["certificate_risk"], state["dependency_risk"], state["secret_risk"], state["rbac_risk"], state["authentication_risk"]], dtype=float)
        new = np.clip(risks * (1.0 - 0.9 * eff), 0.0, 1.0)
        state["certificate_risk"], state["dependency_risk"], state["secret_risk"], state["rbac_risk"], state["authentication_risk"] = new.tolist()
        if int(action_id) in (2,6):
            state["patch_level"] = float(np.clip(state.get("patch_level", 0.5) + 0.1, 0.0, 1.0))
        if int(action_id) in (1,3):
            state["attack_probability"] = float(np.clip(state.get("attack_probability", 0.0) * 0.9, 0.0, 1.0))
        if int(action_id) == 5:
            state["authentication_risk"] = float(np.clip(state.get("authentication_risk", 0.1) * 0.2, 0.0, 1.0))
        return state

    def clear(self):
        self.queue.clear()

