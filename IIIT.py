def run_pipeline():
    # Save hyperparameters
    hyper = vars(cfg).copy()
    hyper["device_used"] = DEVICE
    with open(os.path.join(cfg.OUT_DIR, "hyperparameters.json"), "w") as f:
        json.dump(hyper, f, indent=2)

    # Train models (shorter timesteps for Colab)
    dqn = train_dqn(total_timesteps=cfg.TIMESTEPS_SMALL, seed=cfg.SEED)
    a2c = train_a2c(total_timesteps=cfg.TIMESTEPS_SMALL, seed=cfg.SEED)
    ppo = train_ppo(total_timesteps=cfg.TIMESTEPS_SMALL, seed=cfg.SEED)
    sec = train_secchaos_ppo(total_timesteps=cfg.TIMESTEPS_SMALL, seed=cfg.SEED)

    models = {"DQN": dqn, "A2C": a2c, "PPO": ppo, "SecChaosPPO": sec}

    # Evaluate
    all_results = {}
    for name, model in models.items():
        logger.info(f"Evaluating {name} ...")
        per_eps = evaluate_model(model, n_episodes=cfg.N_EVAL)
        # compute summary metrics per episode
        ep_metrics = [compute_episode_metrics(h) for h in per_eps]
        df = pd.DataFrame(ep_metrics)
        df.to_csv(os.path.join(cfg.OUT_DIR, f"{name}_metrics.csv"), index=False)
        all_results[name] = {"per_episode": ep_metrics, "rewards": [m["episode_reward"] for m in ep_metrics], "actions": [h.get("actions",[]) for h in per_eps], "summary": df.mean().to_dict()}

    # Random baseline
    logger.info("Evaluating Random policy ...")
    per_eps = evaluate_model(None, n_episodes=cfg.N_EVAL)
    ep_metrics = [compute_episode_metrics(h) for h in per_eps]
    df_rand = pd.DataFrame(ep_metrics); df_rand.to_csv(os.path.join(cfg.OUT_DIR, "Random_metrics.csv"), index=False)
    all_results["Random"] = {"per_episode": ep_metrics, "rewards": [m["episode_reward"] for m in ep_metrics], "actions":[h.get("actions",[]) for h in per_eps], "summary": df_rand.mean().to_dict()}

    # Save combined summary
    summary_df = pd.DataFrame({k: v["summary"] for k,v in all_results.items()}).T
    summary_df.to_csv(os.path.join(cfg.OUT_DIR, "results.csv"))

    # Statistical analysis on rewards
    rewards_map = {k: v["rewards"] for k,v in all_results.items()}
    anova_res = run_anova_on_rewards(rewards_map)
    with open(os.path.join(cfg.OUT_DIR, "anova_results.json"), "w") as f:
        json.dump(anova_res, f, indent=2)
    tukey_res = run_tukey(rewards_map)
    tukey_res["summary_df"].to_csv(os.path.join(cfg.OUT_DIR, "tukey_results.csv"), index=False)
    # Cohen's d pairwise
    coh = {}
    names = list(rewards_map.keys())
    for i in range(len(names)):
        for j in range(i+1, len(names)):
            coh[f"{names[i]} vs {names[j]}"] = cohens_d(rewards_map[names[i]], rewards_map[names[j]])
    pd.Series(coh).to_csv(os.path.join(cfg.OUT_DIR, "cohens_d.csv"))

    # Visualizations
    # learning curves
    plot_learning_curves({k: v["rewards"] for k,v in all_results.items()}, os.path.join(cfg.OUT_DIR, "learning_curves.png"))
    # bar metric comparisons
    plot_bar_from_summary({k:v["summary"] for k,v in all_results.items()}, "risk_reduction", os.path.join(cfg.OUT_DIR, "risk_reduction.png"), ylabel="Risk Reduction")
    plot_bar_from_summary({k:v["summary"] for k,v in all_results.items()}, "attack_success_rate", os.path.join(cfg.OUT_DIR, "attack_success.png"), ylabel="Attack Success Rate")
    plot_bar_from_summary({k:v["summary"] for k,v in all_results.items()}, "availability", os.path.join(cfg.OUT_DIR, "availability.png"), ylabel="Availability")
    plot_bar_from_summary({k:v["summary"] for k,v in all_results.items()}, "mttr", os.path.join(cfg.OUT_DIR, "mttr.png"), ylabel="MTTR")
    plot_bar_from_summary({k:v["summary"] for k,v in all_results.items()}, "resilience_score", os.path.join(cfg.OUT_DIR, "resilience.png"), ylabel="Resilience")
    # dependency graph (final for one env)
    env = SecChaosEnv(seed=cfg.SEED)
    plot_dependency_graph(env.dep_graph, os.path.join(cfg.OUT_DIR, "dependency_graph.png"))
    # action distributions (for trained)
    for k,v in all_results.items():
        plot_action_distribution(v["actions"], os.path.join(cfg.OUT_DIR, f"{k}_actions.png"))

    # Save per-episode metrics csvs combined
    combined_rows=[]
    for alg, dat in all_results.items():
        for ep in dat["per_episode"]:
            row = ep.copy(); row["algorithm"]=alg
            combined_rows.append(row)
    pd.DataFrame(combined_rows).to_csv(os.path.join(cfg.OUT_DIR, "metrics_combined.csv"), index=False)

    logger.info(f"Pipeline complete. Outputs saved to {cfg.OUT_DIR}")
    return all_results

